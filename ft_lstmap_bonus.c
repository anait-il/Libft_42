#include "libft.h"

t_list	*ft_lstmap(t_list *lst, void *(*f)(void *), void (*del)(void *))
{
	t_list	*new;
	t_list	*head_new;

	head_new = NULL;
	if (!lst || !f || !del)
		return (NULL);
	while (lst)
	{
		new = ft_lstnew(f(lst->content));
		if (!new)
		{
			ft_lstclear(&head_new, del);
			return (NULL);
		}
		lst = lst->next;
		ft_lstadd_back(&head_new, new);
	}
	return (head_new);
}
